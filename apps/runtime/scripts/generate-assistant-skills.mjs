import { lstat, readFile, readdir, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';

const runtimeRoot = resolve(import.meta.dirname, '..');
const sourceRoot = resolve(runtimeRoot, '../../packages/yuanpu-assistant/skills');
const output = resolve(runtimeRoot, 'src/assistant-skill-assets.generated.ts');
const files = [];

async function collect(directory, prefix) {
  for (const name of (await readdir(directory)).sort()) {
    if (name.startsWith('.')) continue;
    const path = join(directory, name);
    const info = await lstat(path);
    if (info.isSymbolicLink()) throw new Error(`Bundled assistant skill contains a symlink: ${path}`);
    const relativePath = prefix ? `${prefix}/${name}` : name;
    if (info.isDirectory()) await collect(path, relativePath);
    else if (info.isFile()) files.push({ path: relativePath, base64: (await readFile(path)).toString('base64') });
    else throw new Error(`Unsupported bundled assistant skill entry: ${path}`);
  }
}

await collect(sourceRoot, '');
if (files.reduce((sum, file) => sum + file.base64.length, 0) > 2_800_000) {
  throw new Error('Bundled assistant skills exceed the SEA asset budget.');
}
const generated = `// Generated by scripts/generate-assistant-skills.mjs.\n`
  + `export const bundledAssistantSkillFiles: readonly { path: string; base64: string }[] = ${JSON.stringify(files)};\n`;
let previous;
try { previous = await readFile(output, 'utf8'); } catch { /* first build */ }
if (previous !== generated) await writeFile(output, generated);
